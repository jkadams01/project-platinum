"""Make every impossible evolution possible in data/species.json.

Single-player game: no trading, no link cable, no clock, no Alola/Galar
locations, no Legends: Arceus move styles.  73 evolution edges in the veekun
dump cannot be performed.  This script rewrites them under the owner's four
rules (docs/research/evolution-audit.md section 9):

    1. trade                  -> level up at a chosen level
    2. trade + held item      -> level up while holding that item
    3. item-gated impossible  -> level up while holding that item
    4. anything else wacky    -> level up (or, where a plain level would break
                                a sibling branch, an explicit use-item route)

and deletes the 11 edges that are impossible *and* redundant, because a
blanket level-up there would destroy a working branch (Eevee is the extreme
case: two bare level-up edges would eat all eight other Eeveelutions).

    python tools/fix_evolutions.py              # dry run, prints the diff
    python tools/fix_evolutions.py --apply      # rewrite data/species.json
    python tools/fix_evolutions.py --markdown   # emit the design table
    python tools/fix_evolutions.py --verify     # audit only, no table

Idempotent: re-running after --apply reports "already applied" and writes
nothing.  data/species.json is regenerated by tools/build_species.py, which
reads the raw veekun CSVs and knows nothing about this pass -- so this script
must be re-run after every build_species.py run.

Shape note: the replacements use the vocabulary data/species.json already
speaks -- method "level-up" plus "level" / "heldItem" (see DATA_CONTRACT 1).
"level up while holding said item" is exactly {"method":"level-up",
"heldItem":<item>}, which 20 edges in the file already use (Gligar, Happiny),
so no new method string and no contract change is needed.
"""

