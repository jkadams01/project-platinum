# Methods and condition keys that cannot be performed in this game.  Used by
# the verifier, which must report zero of them after --apply.
DEAD_METHODS = set([
    'trade', 'use-move', 'three-critical-hits', 'strong-style-move',
    'agile-style-move', 'recoil-damage', 'take-damage',
    'three-defeated-bisharp', 'meltan-candies', 'spin', 'tower-of-darkness',
    'tower-of-waters', 'in-battle-level-up', 'gimmighoul-coins',
])
DEAD_KEYS = set(['timeOfDay', 'location', 'beauty', 'upsideDown', 'needsRain',
                 'tradeSpecies'])
# knownMove edges whose move no species can teach the pre-evolution.
DEAD_KNOWN_MOVES = set(['barb-barrage'])


def load():
    with open(SPECIES, encoding='utf-8') as fh:
        return json.load(fh)


def save(data):
    with open(SPECIES, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, separators=(',', ':'), sort_keys=True)
        fh.write('\n')


def find(edges, to, method):
    hits = [i for i, e in enumerate(edges)
            if e.get('to') == to and e.get('method') == method]
    return hits


def audit(data):
    """Return the list of still-impossible edges."""
    bad = []
    for sp in data:
        for e in sp.get('evolutions', []):
            why = None
            if e.get('method') in DEAD_METHODS:
                why = 'method=' + str(e.get('method'))
            else:
                dead = sorted(DEAD_KEYS.intersection(e.keys()))
                if dead:
                    why = 'condition=' + ','.join(dead)
                elif e.get('knownMove') in DEAD_KNOWN_MOVES:
                    why = 'unlearnable knownMove=' + str(e.get('knownMove'))
                elif (e.get('method') == 'level-up'
                      and len(set(e.keys()) - set(['to', 'method'])) == 0):
                    why = 'bare level-up: no level, no condition'
            if why:
                bad.append((sp['id'], sp['name'], e.get('to'), why))
    return bad


def apply_table(data, verbose=True):
    by_id = dict((sp['id'], sp) for sp in data)
    changed = skipped = 0
    errors = []
    # Deletions last, and by descending index, so earlier indices stay valid.
    for frm, to, method, old, action, new, _why in TABLE:
        sp = by_id.get(frm)
        if sp is None:
            errors.append('dex %d missing from species.json' % frm)
            continue
        edges = sp.setdefault('evolutions', [])
        hits = find(edges, to, method)
        if not hits:
            # Idempotence: is the target state already in place?
            if action == 'delete':
                skipped += 1
                continue
            want = dict(new)
            want['to'] = to
            if any(e == want for e in edges):
                skipped += 1
                continue
            errors.append('%s #%d -> %d: no %s edge and no converted edge either'
                          % (sp['name'], frm, to, method))
            continue
        if len(hits) > 1:
            errors.append('%s #%d -> %d: %d edges share method %s'
                          % (sp['name'], frm, to, len(hits), method))
            continue
        i = hits[0]
        edge = edges[i]
        expect = dict(old)
        expect['to'] = to
        expect['method'] = method
        if edge != expect:
            errors.append('%s #%d -> %d: edge is %s, design expected %s'
                          % (sp['name'], frm, to, json.dumps(edge, sort_keys=True),
                             json.dumps(expect, sort_keys=True)))
            continue
        if action == 'delete':
            edges.pop(i)
            if verbose:
                print('  DELETE  %-14s #%-4d -> %-4d  %s' % (sp['name'], frm, to, method))
        else:
            want = dict(new)
            want['to'] = to
            edges[i] = want
            if verbose:
                print('  REWRITE %-14s #%-4d -> %-4d  %s  ==>  %s'
                      % (sp['name'], frm, to, method, json.dumps(want, sort_keys=True)))
        changed += 1
    return changed, skipped, errors


def markdown():
    rows = ['| from | to | old method | old condition | new method | new condition | why |',
            '|---|---|---|---|---|---|---|']
    data = load()
    name = dict((sp['id'], sp['name']) for sp in data)
    for frm, to, method, old, action, new, why in TABLE:
        oldc = ', '.join('`%s=%s`' % (k, old[k]) for k in sorted(old)) or '--'
        if action == 'delete':
            nm, nc = '**DELETE**', '--'
        else:
            nm = '`%s`' % new['method']
            nc = ', '.join('`%s=%s`' % (k, new[k]) for k in sorted(new) if k != 'method') or '--'
        rows.append('| %s (%d) | %s (%d) | `%s` | %s | %s | %s | %s |'
                    % (name.get(frm, '?'), frm, name.get(to, '?'), to, method, oldc, nm, nc, why))
    return '\n'.join(rows)


def main(argv):
    if '--markdown' in argv:
        print(markdown())
        return 0

    data = load()
    before = audit(data)
    print('impossible edges before: %d' % len(before))

    if '--verify' in argv:
        for row in before:
            print('  #%-4d %-14s -> %-4d  %s' % row)
        return 0 if not before else 1

    print('design table: %d edges (%d rewrite, %d delete)'
          % (len(TABLE),
             len([r for r in TABLE if r[4] == 'convert']),
             len([r for r in TABLE if r[4] == 'delete'])))
    changed, skipped, errors = apply_table(data)
    print('applied %d, already-applied %d, errors %d' % (changed, skipped, len(errors)))
    for e in errors:
        print('  ERROR ' + e)
    if errors:
        print('REFUSING to write: the data does not match the design table.')
        return 1

    after = audit(data)
    print('impossible edges after: %d' % len(after))
    for row in after:
        print('  STILL IMPOSSIBLE #%-4d %-14s -> %-4d  %s' % row)

    if '--apply' not in argv:
        print('dry run: data/species.json untouched (pass --apply to write)')
        return 0 if not after else 1

    if changed == 0:
        print('nothing to write: already applied')
        return 0 if not after else 1

    save(data)
    # Assert on content, not on exit code: re-read from disk and re-audit.
    check = audit(load())
    print('re-read from disk: %d impossible edges' % len(check))
    if check:
        print('FAILED: impossible edges survived the write')
        return 1
    print('wrote %s' % SPECIES)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
